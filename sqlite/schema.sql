-- Home System schema for SQLite, the third option behind DB_SELECT.
--
-- Apply it with:
--   mise run migrate          (or `pnpm migrate` — same file, same connection)
--   or: sqlite3 data/homesystem.db < sqlite/schema.sql
--
-- It is the Postgres schema in supabase/schema.sql with three substitutions,
-- because SQLite has three fewer types than that file needs:
--
--   text[] / jsonb  ->  text holding JSON, read and written whole
--   boolean         ->  integer 0 / 1
--   numeric         ->  real, except money, which is also real (see below)
--
-- Money as `real` is a deliberate choice and not an oversight. Every figure
-- here is rupees-and-paise computed in JavaScript, where it is already a
-- double: storing it as an integer number of paise would make this driver the
-- only one with a different idea of what a price is, and lib/ is where the
-- arithmetic is tested. If this ever becomes an accounting ledger, change all
-- three drivers together.
--
-- No row-level security, because there is nothing to secure it against: a
-- SQLite database is a file, and whoever can read the file has the data. That
-- is the honest difference from the hosted options — see docs/README.md.

create table if not exists categories (
  id        text primary key,
  name      text not null default '',
  position  integer not null default 0
);

create table if not exists items (
  id          text primary key,
  category_id text not null references categories (id) on delete cascade,
  name        text not null default '',
  room        text not null default '',
  qty         real not null default 0 check (qty >= 0),
  unit        text not null default 'pc',
  min         real not null default 0 check (min >= 0),
  tags        text not null default '[]',
  aliases     text not null default '[]',
  patterns    text not null default '[]',
  position    integer not null default 0
);

create index if not exists items_category_idx on items (category_id, position);

create table if not exists bills (
  -- Generated by the driver with crypto.randomUUID(), so a bill id means the
  -- same thing in all three databases.
  id         text primary key,
  date       text not null,
  store      text not null,
  note       text not null default '',
  total      real not null,
  created_at text not null
);

create index if not exists bills_date_idx on bills (date desc);

create table if not exists bill_items (
  id         integer primary key autoincrement,
  bill_id    text not null references bills (id) on delete cascade,
  name       text not null,
  key        text not null,
  -- Deliberately NOT a foreign key to items, exactly as in Postgres: deleting
  -- an item must not delete what you paid for it.
  item_id    text,
  category   text,
  qty        real not null check (qty > 0),
  unit       text not null,
  cost       real not null check (cost >= 0),
  base       text not null,
  base_qty   real not null check (base_qty > 0),
  unit_price real not null check (unit_price >= 0)
);

create index if not exists bill_items_bill_idx on bill_items (bill_id);
create index if not exists bill_items_key_idx on bill_items (key);
create index if not exists bill_items_item_idx on bill_items (item_id);

create table if not exists subscriptions (
  id          text primary key,
  name        text not null default '',
  type        text not null default '',
  tag         text not null default '',
  holder      text not null default '',
  shareable   integer not null default 0,
  share_count integer check (share_count is null or share_count >= 1),
  cost        real not null default 0 check (cost >= 0),
  cycle       text not null default 'monthly',
  position    integer not null default 0
);

-- The shared family calendar. One row per occurrence; there is no recurrence
-- (lib/calendar.ts says why). The column names follow the Postgres table so
-- that reading one schema teaches you the other: `on_date` and `at_time`
-- because `date` and `time` are type names there, and both times are text
-- because '' means all day, which is not a time.
create table if not exists events (
  id             text primary key,
  on_date        text not null,
  at_time        text not null default '',
  end_time       text not null default '',
  kind           text not null default '',
  title          text not null default '',
  venue          text not null default '',
  link           text not null default '',
  people         text not null default '[]',
  rsvp           text not null default '{}',
  reservation    text not null default '',
  reserved_under text not null default '',
  created_by     text not null default '',
  notes          text not null default '',
  comments       text not null default '[]'
);

create index if not exists events_date_idx on events (on_date, at_time);

-- Who lives here. The calendar points at these people by name, so this is
-- data rather than configuration.
create table if not exists family (
  id       text primary key,
  name     text not null default '',
  role     text not null default '',
  position integer not null default 0
);

-- What was asked of the chat, a day at a time. The day is the primary key, so
-- an append is an upsert.
create table if not exists chats (
  day      text primary key,
  messages text not null default '[]'
);

-- Smart home: the edge controllers on the network, and the devices each owns.
-- No token column anywhere — `token_env` names the .env key the API reads at
-- request time, so the secret is never in this file or in a copy of it.
create table if not exists controllers (
  id        text primary key,
  name      text not null default '',
  url       text not null default '',
  token_env text not null default 'EDGE_TOKEN',
  notes     text not null default '',
  position  integer not null default 0
);

create table if not exists devices (
  id            text primary key,
  name          text not null default '',
  kind          text not null default 'switch',
  room          text not null default '',
  controller_id text references controllers (id) on delete cascade,
  address       text not null default '',
  min_setpoint  real,
  max_setpoint  real,
  modes         text not null default '[]',
  read_only     integer not null default 0,
  position      integer not null default 0
);

-- Deliberately NOT unique, for the same reason the other two drivers say: one
-- address per controller is a real rule, enforced by `normalizeDevices`, so
-- that swapping two devices' addresses inside one transaction cannot fail
-- halfway through.
create index if not exists devices_address_idx on devices (controller_id, address);

create index if not exists devices_room_idx on devices (room, position);
